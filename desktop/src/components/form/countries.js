const norm = (s) => String(s ?? "").toLocaleUpperCase("en").normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/İ/g, "I").replace(/[^A-Z0-9]/g, "");
const INDEX = new Map(COUNTRIES.map((c) => [norm(c), c]));

/** Okunan/eski bir değeri listedeki karşılığına çevirir ("Turkey" → "TÜRKİYE"); tanınmazsa null */
export function resolveCountry(value) {
  const k = norm(value);
  return INDEX.get(k) || ALIASES[k] || null;
}
