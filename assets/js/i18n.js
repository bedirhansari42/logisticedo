const LANG_KEY = "lgx.lang";
const listeners = new Set();
let current = detect();

function detect() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "tr" || saved === "en") return saved;
  } catch { /* depolama kapalı olabilir */ }
  const nav = (navigator.language || "tr").toLowerCase();
  return nav.startsWith("tr") ? "tr" : "en";
}

export function getLang() { return current; }

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.tr[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    el.dataset.i18nAttr.split(";").forEach((pair) => {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    });
  });
  document.documentElement.lang = current;
  const titleKey = document.documentElement.dataset.titleKey;
  if (titleKey) document.title = t(titleKey);
}

export function setLang(lang) {
  if (lang !== "tr" && lang !== "en") return;
  const prev = current;
  current = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* yoksay */ }
  applyI18n();
  document.querySelectorAll(".lang-switch button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
  if (prev !== lang) listeners.forEach((fn) => fn(lang, prev));
}

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }
